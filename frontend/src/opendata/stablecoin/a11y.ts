// Keyboard support for the dashboard's tablists and radio groups (WAI-ARIA
// Authoring Practices): arrow keys move and wrap, Home and End jump to the
// ends. Pure, so it is unit-tested.
export function rovingIndex(key: string, index: number, count: number): number | null {
  if (count <= 0) return null;
  switch (key) {
    case 'ArrowRight':
    case 'ArrowDown':
      return (index + 1) % count;
    case 'ArrowLeft':
    case 'ArrowUp':
      return (index - 1 + count) % count;
    case 'Home':
      return 0;
    case 'End':
      return count - 1;
    default:
      return null;
  }
}
